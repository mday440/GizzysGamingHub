static const uint8_t bc7_w2[4] = { 0, 21, 43, 64 }, bc7_w3[8] = { 0, 9, 18, 27, 37, 46, 55, 64 },
                     bc7_w4[16] = { 0, 4, 9, 13, 17, 21, 26, 30, 34, 38, 43, 47, 51, 55, 60, 64 };
static uint32_t bc7_rd(const uint8_t *b, uint32_t *pos, uint32_t n) {
    uint32_t v = 0;
    for (uint32_t i = 0; i < n; i++, (*pos)++) v |= (uint32_t)((b[*pos >> 3] >> (*pos & 7)) & 1) << i;
    return v;
}
static uint8_t bc7_interp(uint8_t a, uint8_t b, uint32_t idx, uint32_t bits) {
    uint32_t w = bits == 2 ? bc7_w2[idx] : bits == 3 ? bc7_w3[idx] : bc7_w4[idx];
    return (uint8_t)(((64 - w) * a + w * b + 32) >> 6);
}
/* decode a 16-byte block into 16 RGBA8 texels (row-major 4x4) */
static void bc7_decode(const uint8_t *b, uint8_t out[16][4]) {
    static const uint8_t NS[8] = {3,2,3,2,1,1,1,2}, PB[8] = {4,6,6,6,0,0,0,6}, RB[8] = {0,0,0,0,2,2,0,0}, ISB[8] = {0,0,0,0,1,0,0,0},
        CB[8] = {4,6,5,7,5,7,7,5}, AB[8] = {0,0,0,0,6,8,7,5}, EPB[8] = {1,0,0,1,0,0,1,1}, SPB[8] = {0,1,0,0,0,0,0,0}, IB[8] = {3,3,2,2,2,2,4,2}, IB2[8] = {0,0,0,0,3,2,0,0};
    int m = 0; while (m < 8 && !((b[0] >> m) & 1)) m++;
    if (m == 8) { for (int i = 0; i < 16; i++) out[i][0] = out[i][1] = out[i][2] = out[i][3] = 0; return; }
    uint32_t pos = (uint32_t)m + 1;
    uint32_t part = bc7_rd(b, &pos, PB[m]), rot = bc7_rd(b, &pos, RB[m]), isel = bc7_rd(b, &pos, ISB[m]);
    int ns = NS[m];
    uint32_t ep[3][2][4] = {{{0}}};
    for (int c = 0; c < 3; c++) for (int s = 0; s < ns; s++) for (int e = 0; e < 2; e++) ep[s][e][c] = bc7_rd(b, &pos, CB[m]);
    if (AB[m]) for (int s = 0; s < ns; s++) for (int e = 0; e < 2; e++) ep[s][e][3] = bc7_rd(b, &pos, AB[m]);
    uint32_t pb[3][2] = {{0}}; int haspb = EPB[m] || SPB[m];
    if (EPB[m]) for (int s = 0; s < ns; s++) for (int e = 0; e < 2; e++) pb[s][e] = bc7_rd(b, &pos, 1);
    if (SPB[m]) for (int s = 0; s < ns; s++) { pb[s][0] = pb[s][1] = bc7_rd(b, &pos, 1); }
    uint8_t col[3][2][4];
    for (int s = 0; s < ns; s++) for (int e = 0; e < 2; e++) for (int c = 0; c < 4; c++) {
        uint32_t bits = c < 3 ? CB[m] : AB[m];
        if (!bits) { col[s][e][c] = 255; continue; }
        uint32_t v = ep[s][e][c];
        if (haspb) { v = (v << 1) | pb[s][e]; bits++; }
        v <<= 8 - bits; v |= v >> bits;
        col[s][e][c] = (uint8_t)v;
    }
    uint8_t sub[16];
    for (int i = 0; i < 16; i++) sub[i] = ns == 1 ? 0 : ns == 2 ? bc7_part2[part * 16 + i] : bc7_part3[part * 16 + i];
    int anc1 = ns == 2 ? bc7_anchor2[part] : ns == 3 ? bc7_anchor3a[part] : -1, anc2 = ns == 3 ? bc7_anchor3b[part] : -1;
    uint32_t i1[16], i2[16] = {0};
    for (int i = 0; i < 16; i++) i1[i] = bc7_rd(b, &pos, IB[m] - ((i == 0 || i == anc1 || i == anc2) ? 1 : 0));
    if (IB2[m]) for (int i = 0; i < 16; i++) i2[i] = bc7_rd(b, &pos, IB2[m] - (i == 0 ? 1 : 0));
    for (int i = 0; i < 16; i++) {
        int s = sub[i]; uint8_t *o = out[i];
        uint32_t ci = i1[i], cbits = IB[m], ai = i1[i], abits = IB[m];
        if (IB2[m]) { if (isel) { ci = i2[i]; cbits = IB2[m]; } else { ai = i2[i]; abits = IB2[m]; } }
        for (int c = 0; c < 3; c++) o[c] = bc7_interp(col[s][0][c], col[s][1][c], ci, cbits);
        o[3] = bc7_interp(col[s][0][3], col[s][1][3], ai, abits);
        if (rot) { uint8_t t = o[3]; o[3] = o[rot - 1]; o[rot - 1] = t; }
    }
}
